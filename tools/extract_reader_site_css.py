#!/usr/bin/env python3
"""Extract article-only rules unchanged from the website (no npm/build required).
Run from any directory. --check fails if the bundled reader CSS has drifted.
Never reads notes, imports author styles, or modifies the website's behaviour.
"""
from pathlib import Path
import argparse
import hashlib
import re
import os

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'resources/Reader/site-article.css'


def blocks(css):
    # Scan strings/comments correctly: braces in CSS strings are not block ends.
    pos = 0
    while pos < len(css):
        start = pos
        depth, quote, comment, opened = 0, '', False, None
        while pos < len(css):
            ch = css[pos]
            if comment:
                if css[pos:pos+2] == '*/': comment = False; pos += 2; continue
            elif quote:
                if ch == '\\': pos += 2; continue
                if ch == quote: quote = ''
            elif css[pos:pos+2] == '/*': comment = True; pos += 2; continue
            elif ch in "\"'": quote = ch
            elif ch == '{':
                if depth == 0: opened = pos
                depth += 1
            elif ch == '}':
                depth -= 1
                if depth == 0 and opened is not None:
                    prelude = re.sub(r'/\*.*?\*/', '', css[start:opened], flags=re.S).strip()
                    yield prelude, css[opened+1:pos]
                    pos += 1
                    break
            pos += 1
        else: break


def select(css, predicate):
    out = []
    for selector, body in blocks(css):
        if selector.startswith('@media'):
            inner = select(body, predicate)
            if inner: out.append(f'{selector} {{\n{inner}\n}}')
        elif not selector.startswith('@'):
            selectors = [s.strip() for s in selector.split(',')]
            if selectors and all(predicate(s) for s in selectors):
                out.append(f'{selector} {{{body}}}')
    return '\n\n'.join(out)


def generate(site_root):
    page = (site_root / 'src/pages/blog/[slug].astro').read_text()
    css = page.split('<style is:global>', 1)[1].split('</style>', 1)[0] if '<style is:global>' in page else page.split('<style>', 1)[1].split('</style>', 1)[0]
    global_css = (site_root / 'src/styles/global.css').read_text()
    tokens = select(global_css, lambda s: s in (':root', "[data-theme='dark']"))
    base = select(global_css, lambda s: bool(re.fullmatch(r'h[1-6]', s)))
    article = select(css, lambda s: bool(re.match(r'(?:html\[data-theme=[\'"]dark[\'"]\]\s+)?\.content(?:\b|[\s.:#>+~\[])', s)))
    header = select(css, lambda s: s == '.post-header' or s == '.post-header h1' or s == '.meta')
    # Keep every property/value in article rules verbatim; only scope to the
    # native article, so private memo previews keep their established styling.
    article = re.sub(r'\.content\b', '#content.site-content', article)
    base = re.sub(r'(?<![\w-])(h[1-6])(?![\w-])', r'#reader.site-reader \1', base)
    header = header.replace('.post-header h1', '#reader.site-reader #title').replace('.post-header', '#reader.site-reader #article-header').replace('.meta', '#reader.site-reader #meta')
    tokens = tokens.replace(':root', 'html.lb-article-reader').replace("[data-theme='dark']", "html.lb-article-reader[data-theme='dark']")
    source_hash = hashlib.sha256((global_css + css).encode()).hexdigest()
    return ('/* GENERATED by tools/extract_reader_site_css.py; do not hand-edit.\n'
            ' * Exact website article declarations; native scopes only.\n'
            f' * Source SHA256: {source_hash}\n */\n' + tokens + '\n\n' + base + '\n\n' + header + '\n\n' + article + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--site-root', default=os.environ.get('LONGBLOG_SITE_ROOT'),
                        help='Explicit upstream checkout (or LONGBLOG_SITE_ROOT); never inferred')
    args = parser.parse_args()
    if not args.site_root:
        parser.error('upstream source required: use --site-root or LONGBLOG_SITE_ROOT; normal builds use bundled CSS')
    site_root = Path(args.site_root).expanduser().resolve()
    for source in ('src/pages/blog/[slug].astro', 'src/styles/global.css'):
        if not (site_root / source).is_file():
            parser.error(f'missing upstream source: {site_root / source}')
    result = generate(site_root)
    if args.check:
        if not DEST.exists() or DEST.read_text() != result: raise SystemExit('Reader site CSS is stale; run extract_reader_site_css.py')
        print('Reader site CSS parity: OK')
    else:
        DEST.write_text(result)
        print(f'Generated {DEST.relative_to(ROOT)} ({len(result)} characters)')
